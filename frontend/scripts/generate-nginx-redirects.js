// Generate nginx redirect map include from seo-data.js
const fs = require("fs");
const path = require("path");
const { SERVICES, LOCATIONS, SERVICE_REDIRECTS, PAGE_REDIRECTS } = require("./seo-data");

const lines = [];
lines.push("# Auto-generated by frontend/scripts/generate-nginx-redirects.js — do not edit by hand.");
lines.push("# Exact URI → destination (used with map $uri $carenest_redirect).");
lines.push("");

Object.entries(PAGE_REDIRECTS).forEach(([from, to]) => {
  lines.push(`${from} ${to};`);
});

Object.entries(SERVICE_REDIRECTS).forEach(([fromSlug, toSlug]) => {
  lines.push(`/services/${fromSlug} /services/${toSlug};`);
});

LOCATIONS.forEach((city) => {
  Object.entries(SERVICE_REDIRECTS).forEach(([fromSlug, toSlug]) => {
    lines.push(`/locations/${city}/${fromSlug} /locations/${city}/${toSlug};`);
  });
});

const body = lines.join("\n") + "\n";
const outFrontend = path.join(__dirname, "..", "public", "redirects.map.txt");
const outNginx = path.join(__dirname, "..", "..", "deploy", "nginx", "redirects.map");
fs.writeFileSync(outFrontend, body);
fs.writeFileSync(outNginx, body);

const count =
  Object.keys(PAGE_REDIRECTS).length +
  Object.keys(SERVICE_REDIRECTS).length +
  LOCATIONS.length * Object.keys(SERVICE_REDIRECTS).length;

console.log(`Wrote ${count} redirects to:`);
console.log(`  ${outNginx}`);
console.log(`  ${outFrontend}`);
console.log(`Primary services retained: ${SERVICES.join(", ")}`);
